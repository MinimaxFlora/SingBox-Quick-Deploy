#!/usr/bin/env bash
# =============================================================================
#  build.sh · 生成单文件发布版 dist/sbqd.sh
#  用法：build/build.sh [VERSION]
# =============================================================================
set -Eeuo pipefail

BUILD_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd -- "${BUILD_DIR}/.." && pwd)
cd -- "${ROOT}"

VERSION=${1:-}
if [[ -z ${VERSION} ]]; then
  if VERSION=$(git describe --tags --abbrev=0 2> /dev/null); then
    VERSION=${VERSION#v}
  elif [[ -f VERSION ]]; then
    VERSION=$(tr -d '[:space:]' < VERSION)
  else
    VERSION='0.1.0'
  fi
fi
VERSION=${VERSION#v}

for tool in base64 sha256sum; do
  command -v "${tool}" > /dev/null 2>&1 || {
    printf 'build: missing %s\n' "${tool}" >&2
    exit 1
  }
done

mkdir -p dist
OUT="dist/sbqd.sh"
TMP="${OUT}.tmp"

python_b64=$(base64 -w 0 assets/subserver.py 2> /dev/null || base64 assets/subserver.py | tr -d '\n')
build_date=$(date -u '+%Y-%m-%dT%H:%M:%SZ')

{
  printf '#!/usr/bin/env bash\n'
  printf '# =============================================================================\n'
  printf '#  SingBox-Quick-Deploy %s (single-file build)\n' "${VERSION}"
  printf '#  Built: %s\n' "${build_date}"
  printf '#  Source: https://github.com/MinimaxFlora/SingBox-Quick-Deploy\n'
  printf '#  This file is generated by build/build.sh — do not edit manually.\n'
  printf '# =============================================================================\n'
  printf 'set -Eeuo pipefail\n\n'
  printf 'SBQD_VERSION=%q\n' "${VERSION}"
  printf 'SBQD_SELF=$(readlink -f -- "${BASH_SOURCE[0]}" 2>/dev/null || printf "%%s" "${BASH_SOURCE[0]}")\n'
  printf 'SBQD_EMBEDDED_SUBSERVER=%q\n\n' "${python_b64}"

  while IFS= read -r module; do
    [[ -n ${module} ]] || continue
    printf '\n# ===== %s =====\n' "${module}"
    cat "src/${module}"
  done < src/modules.txt

  printf '\n# ===== entry =====\n'
  printf 'sbqd_main "$@"\n'
} > "${TMP}"

bash -n "${TMP}" || {
  printf 'build: syntax check failed\n' >&2
  exit 1
}

mv -f -- "${TMP}" "${OUT}"
chmod 755 "${OUT}"

sha256sum "${OUT}" > "${OUT}.sha256"
printf 'built %s (%s bytes, version %s)\n' \
  "${OUT}" "$(wc -c < "${OUT}" | tr -d ' ')" "${VERSION}"
